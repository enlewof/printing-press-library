// contactFormPath mirrors internal/client's contactFormPath constant (see
// that file's comment for why the cli and client packages each keep their
// own copy of this literal -- forkableGraphQLPath/graphqlPath already do
// the same for the GraphQL route).
const contactFormPath = "/submit_contact_form"

// mealFeedbackCategories are the accepted --category values, each mapped to
// one of Forkable's own contact-form subjects (see mealFeedbackSubjectFor).
// Subjects unrelated to a delivered-meal problem (Change Admin, Account
// Settings, Billing & Payment, Suggest an Improvement, Request Meal
// Adjustment) are intentionally not exposed here -- out of scope for this
// command.
var mealFeedbackCategories = []string{"missing-item", "wrong-item", "quality", "late", "other"}

// mealFeedbackSubjectFor maps a --category to the exact subject string
// Forkable's contact form expects (module 29822 in mc/js/app.*.js: base
// subjects ["Missing Meal","Change Admin"], extended
// ["Delivery Status","Request Meal Adjustment","Account Settings",
// "Billing & Payment","Report Issue","Suggest an Improvement",
// "General Inquiry"]). Returns ok=false for anything not in
// mealFeedbackCategories.
func mealFeedbackSubjectFor(category string) (subject string, ok bool) {
	switch category {
	case "missing-item":
		return "Missing Meal", true
	case "wrong-item", "quality":
		return "Report Issue", true
	case "late":
		return "Delivery Status", true
	case "other":
		return "General Inquiry", true
	default:
		return "", false
	}
}

const mealFeedbackMaxNoteLen = 4096

// MealFeedbackEntry is one line in the local delivery-issue ledger -- a
// record of what this CLI attempted/sent to Forkable support, kept
// independent of the support ticket itself so the member has their own copy.
type MealFeedbackEntry struct {
	DeliveryID int64     `json:"delivery_id"`
	Category   string    `json:"category"`
	Subject    string    `json:"subject"`
	Note       string    `json:"note"`
	Venue      string    `json:"venue,omitempty"`
	Item       string    `json:"item,omitempty"`
	PieceID    string    `json:"piece_id,omitempty"`
	Submitted  bool      `json:"submitted"`
	CLI        string    `json:"cli"`
	Version    string    `json:"version"`
	Timestamp  time.Time `json:"timestamp"`
}

func mealFeedbackFilePath() (string, error) {
	dir, err := cliutil.DataDir()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", fmt.Errorf("creating meal-feedback data dir: %w", err)
	}
	return filepath.Join(dir, "meal-feedback.jsonl"), nil
}

func appendMealFeedback(entry MealFeedbackEntry) error {
	p, err := mealFeedbackFilePath()
	if err != nil {
		return err
	}
	f, err := os.OpenFile(p, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
	if err != nil {
		return fmt.Errorf("opening meal-feedback ledger: %w", err)
	}
	defer f.Close()
	return json.NewEncoder(f).Encode(entry)
}

func readMealFeedback() ([]MealFeedbackEntry, error) {
	p, err := mealFeedbackFilePath()
	if err != nil {
		return nil, err
	}
	data, err := os.ReadFile(p)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var entries []MealFeedbackEntry
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		var e MealFeedbackEntry
		if err := json.Unmarshal([]byte(line), &e); err != nil {
			continue
		}
		entries = append(entries, e)
	}
	return entries, nil
}

// composeMealFeedbackMessage builds the contact-form message body. Forkable's
// form has no structured delivery/venue/item/piece field, so this folds that
// context into the free-text message the way a human filling out the same
// form by hand would.
func composeMealFeedbackMessage(deliveryID int64, note, venue, item, pieceID string) string {
	var b strings.Builder
	b.WriteString(note)
	b.WriteString(fmt.Sprintf("\n\n(Sent via forkable-pp-cli meal feedback. Delivery ID: %d", deliveryID))
	if venue != "" {
		b.WriteString(fmt.Sprintf(", venue: %s", venue))
	}
	if item != "" {
		b.WriteString(fmt.Sprintf(", item: %s", item))
	}
	if pieceID != "" {
		b.WriteString(fmt.Sprintf(", piece: %s", pieceID))
	}
	b.WriteString(".)")
	return b.String()
}

// meCore is the minimal `me` projection meal feedback needs -- name and
// email for the contact-form payload. Deliberately narrower than
// promoted_account.go's full current-user query.
type meCore struct {
	FullName string `json:"fullName"`
	Email    string `json:"email"`
}

const meCoreQuery = `query { me { fullName email } }`

func fetchMeCore(ctx context.Context, flags *rootFlags) (meCore, error) {
	data, err := fetchGraphQL(ctx, flags, meCoreQuery)
	if err != nil {
		return meCore{}, err
	}
	var wrap struct {
		Me meCore `json:"me"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return meCore{}, fmt.Errorf("parsing account info: %w", err)
	}
	return wrap.Me, nil
}

type deliveryMarketRow struct {
	ID   int64 `json:"id"`
	Club struct {
		Market struct {
			ID int64 `json:"id"`
		} `json:"market"`
	} `json:"club"`
}

// resolveDeliveryMarketID looks up the market id for deliveryID, matching
// the market_id field the my-account SPA sends alongside a contact-form
// submission. Best-effort: an error or a not-found delivery returns 0 so
// the caller can still submit with market_id omitted rather than fail the
// whole command over a field Forkable's own form only opportunistically
// fills in (see the SPA's `1===this.marketOptions.length?...:...` fallback).
//
// myDeliveries(from: ...) does NOT behave as a ">= from" historical filter
// -- empirically, a far-past `from` (e.g. "2000-01-01", the pattern
// served-history/allowance-burn use for full-history reads) returns zero
// rows, while `from: <today>` reliably returns both the just-delivered and
// the next-upcoming delivery. Since meal feedback targets a delivery a
// member just received, today's date is used rather than a wide floor;
// deliveries far outside that rolling window simply fall back to no
// market_id.
func resolveDeliveryMarketID(ctx context.Context, flags *rootFlags, deliveryID int64) int64 {
	today := time.Now().UTC().Format("2006-01-02")
	query := fmt.Sprintf(`query { myDeliveries (from: "%s") { id club { market { id } } } }`, today)
	data, err := fetchGraphQL(ctx, flags, query)
	if err != nil {
		return 0
	}
	var wrap struct {
		MyDeliveries []deliveryMarketRow `json:"myDeliveries"`
	}
	if err := json.Unmarshal(data, &wrap); err != nil {
		return 0
	}
	for _, d := range wrap.MyDeliveries {
		if d.ID == deliveryID {
			return d.Club.Market.ID
		}
	}
	return 0
}

// submitContactForm POSTs to Forkable's my-account "Contact Support" REST
// endpoint -- see the file header for why this is not a GraphQL mutation.
func submitContactForm(ctx context.Context, flags *rootFlags, body map[string]any) error {
	c, err := flags.newClient()
	if err != nil {
		return err
	}
	_, status, err := c.Post(ctx, contactFormPath, body)
	if err != nil {
		return classifyAPIError(err, flags)
	}
	if status == 401 || status == 403 {
		return fmt.Errorf("not authenticated (HTTP %d): run 'forkable-pp-cli auth login --chrome' after logging in to forkable.com in Chrome", status)
	}
	if status < 200 || status >= 300 {
		return fmt.Errorf("forkable contact-form submission returned HTTP %d", status)
	}
	return nil
}

// newMealFeedbackCmd wraps POST /submit_contact_form -- see the file header.
// It is added as a subcommand of the existing `meal` parent in
// forkable_orders.go, alongside the GraphQL-backed set/set-all/confirm/skip.
func newMealFeedbackCmd(flags *rootFlags) *cobra.Command {
	var category, note, venue, item, pieceID string
	var confirm bool
	cmd := &cobra.Command{
		Use:   "feedback <deliveryId>",
		Short: "Report a problem with a delivered meal to Forkable support (missing/wrong item, quality, etc.)",
		Long: strings.Trim(`
Submits a real support request to Forkable -- the same POST /submit_contact_form
request the my-account app's "Contact Support" modal sends, discovered by
static analysis of the my-account SPA bundle. This is a plain REST call, not
part of the GraphQL surface every other command in this CLI uses.

Forkable routes contact-form submissions by "subject"; --category maps to
Forkable's own subject list:

  missing-item -> "Missing Meal"     wrong-item -> "Report Issue"
  quality      -> "Report Issue"     late       -> "Delivery Status"
  other        -> "General Inquiry"

Forkable's contact form has no separate field for delivery/venue/item/piece,
so those are folded into the message body alongside --note. Building the
request requires two live reads first (your name/email, and the delivery's
market id), so even the no-flags preview below touches the network.

Dry-run by default like every other 'meal' write command: prints the exact
request it would send and stops. Pass --confirm to actually submit it. Every
attempt is also recorded in the local meal-feedback.jsonl ledger.`, "\n"),
		Example: strings.Trim(`
  forkable-pp-cli meal feedback 12345 --category missing-item --note "Rice was missing from the order" --item "Example Item" --venue "Example Venue" --confirm
  forkable-pp-cli meal feedback 12345 --category missing-item --note "no rice" --piece <uuid> --agent`, "\n"),
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 && cmd.Flags().NFlag() == 0 {
				return cmd.Help()
			}
			if dryRunOK(flags) {
				emitDryRunShortCircuit(cmd, flags, "submit a Forkable support request about a delivered meal")
				return nil
			}
			if len(args) < 1 {
				_ = cmd.Usage()
				return usageErr(fmt.Errorf("delivery id is required"))
			}
			deliveryID, err := parseInt64(args[0])
			if err != nil {
				return usageErr(fmt.Errorf("invalid delivery id %q: %w", args[0], err))
			}
			category = strings.ToLower(strings.TrimSpace(category))
			if category == "" {
				category = "other"
			}
			subject, ok := mealFeedbackSubjectFor(category)
			if !ok {
				return usageErr(fmt.Errorf("invalid --category %q: expected one of %s", category, strings.Join(mealFeedbackCategories, ", ")))
			}
			note = strings.TrimSpace(note)
			if note == "" {
				return usageErr(fmt.Errorf("--note is required"))
			}
			if len(note) > mealFeedbackMaxNoteLen {
				note = note[:mealFeedbackMaxNoteLen]
			}

			ctx, cancel := boundCtx(cmd.Context(), flags)
			defer cancel()

			who, err := fetchMeCore(ctx, flags)
			if err != nil {
				return fmt.Errorf("looking up account info for the support request: %w", err)
			}
			marketID := resolveDeliveryMarketID(ctx, flags, deliveryID)

			message := composeMealFeedbackMessage(deliveryID, note, venue, item, pieceID)
			body := map[string]any{
				"name":    who.FullName,
				"email":   who.Email,
				"subject": subject,
				"message": message,
			}
			if marketID != 0 {
				body["market_id"] = marketID
			}

			action := fmt.Sprintf("submit a %q support request to Forkable for delivery %d", subject, deliveryID)
			if !confirmOrPreview(cmd, flags, confirm, action, "POST "+contactFormPath, body) {
				return nil
			}

			submitErr := submitContactForm(ctx, flags, body)
			entry := MealFeedbackEntry{
				DeliveryID: deliveryID,
				Category:   category,
				Subject:    subject,
				Note:       note,
				Venue:      strings.TrimSpace(venue),
				Item:       strings.TrimSpace(item),
				PieceID:    strings.TrimSpace(pieceID),
				Submitted:  submitErr == nil,
				CLI:        "forkable-pp-cli",
				Version:    version,
				Timestamp:  time.Now().UTC(),
			}
			_ = appendMealFeedback(entry) // best-effort local record; submission result below is authoritative
			if submitErr != nil {
				return submitErr
			}

			machineOut := flags.asJSON || flags.agent || !isTerminal(cmd.OutOrStdout())
			if machineOut {
				return printJSONFiltered(cmd.OutOrStdout(), map[string]any{
					"submitted": true,
					"entry":     entry,
				}, flags)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "submitted to Forkable support: %q for delivery %d\n", subject, deliveryID)
			return nil
		},
	}
	cmd.Flags().StringVar(&category, "category", "other", "issue category: "+strings.Join(mealFeedbackCategories, ", "))
	cmd.Flags().StringVar(&note, "note", "", "free-text description of the issue (required)")
	cmd.Flags().StringVar(&venue, "venue", "", "venue name for reference (optional)")
	cmd.Flags().StringVar(&item, "item", "", "menu item name for reference (optional)")
	cmd.Flags().StringVar(&pieceID, "piece", "", "piece UUID from 'deliveries list'/'served-history' for reference (optional)")
	cmd.Flags().BoolVar(&confirm, "confirm", false, "actually submit the request (default: preview only)")

	cmd.AddCommand(newMealFeedbackListCmd(flags))
	return cmd
}

func newMealFeedbackListCmd(flags *rootFlags) *cobra.Command {
	var limit int
	cmd := &cobra.Command{
		Use:   "list",
		Short: "List recent local meal-feedback entries",
		Annotations: map[string]string{
			"mcp:read-only": "true",
		},
		Long: "Lists this CLI's own local record of meal-feedback attempts (see 'meal feedback --help'). The `submitted` field reflects whether the live POST to Forkable succeeded, not whether the ticket was resolved.",
		Example: strings.Trim(`
  forkable-pp-cli meal feedback list
  forkable-pp-cli meal feedback list --limit 5
  forkable-pp-cli meal feedback list --json`, "\n"),
		RunE: func(cmd *cobra.Command, _ []string) error {
			entries, err := readMealFeedback()
			if err != nil {
				return err
			}
			if limit > 0 && limit < len(entries) {
				entries = entries[len(entries)-limit:]
			}
			if entries == nil {
				entries = []MealFeedbackEntry{}
			}
			return printJSONFiltered(cmd.OutOrStdout(), entries, flags)
		},
	}
	cmd.Flags().IntVar(&limit, "limit", 20, "Maximum number of recent entries to return")
	return cmd
}
