// Meal/delivery issue reporting. Forkable's GraphQL surface (the API every
// other command in this CLI uses) has no mutation for "something was wrong
// with this delivery" -- only replacePiece, replaceAllPieces,
// confirmDelivery, and removeDelivery(-ies) (see forkable_orders.go). But
// the my-account SPA's "Contact Support" modal does have a real submission
// path: a plain REST POST to /submit_contact_form, discovered by static
// analysis of the SPA bundle (mc/js/app.*.js -- see
// getSubjectOptions()/submitContactForm() in that bundle's module 29822).
// It is NOT part of the GraphQL API: no query/mutation name, just
// {name, email, subject, message, market_id} POSTed with the same
// x-csrf-token + session-cookie auth as every GraphQL call (see
// internal/client/forkable_csrf.go).
//
// This command wraps that real endpoint. Like every other meal-management
// write in this file, it is DRY-RUN BY DEFAULT and only submits with
// --confirm. Unlike the GraphQL mutations, building an accurate preview
// requires two live reads first (the account's name/email, and the target
// delivery's market id) -- Forkable's contact form has no per-delivery
// field, so the delivery/venue/item/piece context is folded into the
// message body instead. Every attempt (submitted or previewed) is also
// recorded in a local meal-feedback.jsonl ledger so the member has their
// own record independent of whatever happens to the support ticket.
//
// This is a hand-authored file (no "Generated by ..." header) so
// `generate --force` preserves it, matching forkable_orders.go.

